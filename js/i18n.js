const i18n = {
  locale: localStorage.getItem(LOCALE_STORE) || 'it',

  t(key, vars) {
    const val = I18N_DATA[this.locale]?.[key] ?? I18N_DATA.it[key] ?? key;
    if (typeof val !== 'string') return val;
    if (!vars) return val;
    return val.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  },

  setLocale(lang) {
    this.locale = lang;
    localStorage.setItem(LOCALE_STORE, lang);
  },

  nextLocale() {
    const idx = LOCALES.indexOf(this.locale);
    return LOCALES[(idx + 1) % LOCALES.length];
  },
};
